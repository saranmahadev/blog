#!/usr/bin/env node
/**
 * Generates the Imaxt design-canvas artboards from the real site, so the design cannot drift from the code.
 *
 *   pnpm build && node design/tools/build-imaxt-mock.mjs [--height 8000] [--mobile-height 12000]
 *
 * Outputs (in design/mock/):
 *   site.css         src/styles/{tokens,components,imaxt}.css scoped under .dm (dark = .dm.dark)
 *   imaxt-cover.css  just the typographic-cover rules, for artboards that still use mock.css
 *   Imaxt.dc.html, ImaxtMobile.dc.html   the built /imaxt/ Lab page as static artboards
 */
import fs from 'node:fs';
import postcss from 'postcss';
import { parse, parseFragment, serialize } from 'parse5';

const arg = (name, fallback) => {
  const i = process.argv.indexOf(`--${name}`);
  return i > -1 ? Number(process.argv[i + 1]) : fallback;
};
const OUT = 'design/mock';

// ---------- CSS ----------
const scopeSelector = (sel) =>
  sel
    .split(',')
    .map((raw) => {
      const s = raw.trim();
      if (s.startsWith(":root[data-theme='dark']")) return s.replace(":root[data-theme='dark']", '.dm.dark');
      if (s === ':root') return '.dm';
      if (s.startsWith("html[data-theme='dark']")) return s.replace("html[data-theme='dark']", '.dm.dark');
      if (s === 'html' || s === 'body') return '.dm';
      return `.dm ${s}`;
    })
    .join(', ');

function scope(css) {
  const root = postcss.parse(css);
  root.walkRules((rule) => {
    if (rule.parent?.type === 'atrule' && /keyframes$/.test(rule.parent.name)) return;
    rule.selector = scopeSelector(rule.selector);
  });
  return root;
}

const read = (f) => fs.readFileSync(f, 'utf8');
const RESET = `/* Minimal reset (the site gets this from Tailwind's preflight). Zero specificity so components win. */
:where(.dm) *, :where(.dm) *::before, :where(.dm) *::after { box-sizing: border-box; margin: 0; padding: 0; border: 0 solid; }
:where(.dm) h1, :where(.dm) h2, :where(.dm) h3, :where(.dm) h4 { font-size: inherit; font-weight: inherit; }
:where(.dm) a { color: inherit; text-decoration: inherit; }
:where(.dm) ol, :where(.dm) ul { list-style: none; }
:where(.dm) button { font: inherit; color: inherit; background: transparent; cursor: pointer; }
:where(.dm) input, :where(.dm) textarea { font: inherit; color: inherit; }
:where(.dm) img, :where(.dm) svg { display: block; max-width: 100%; }
:where(.dm) table { border-collapse: collapse; }
`;
const sources = ['tokens', 'components', 'imaxt'].map((n) => `/* ---- src/styles/${n}.css ---- */\n${scope(read(`src/styles/${n}.css`)).toString()}`);
fs.writeFileSync(`${OUT}/site.css`, `/* GENERATED by design/tools/build-imaxt-mock.mjs. Do not edit. */\n${RESET}\n${sources.join('\n\n')}\n`);

// Cover-only subset (fonts, tone variables and the .imx-cover rules) for the older artboards.
const coverRoot = postcss.root();
scope(read('src/styles/imaxt.css')).walkRules((rule) => {
  if (rule.parent?.type !== 'root') return;
  if (/imx-cover|\[data-tone|^\.dm$/.test(rule.selector) || /^\.dm, \.dm \.imx-cover/.test(rule.selector)) coverRoot.append(rule.clone());
});
fs.writeFileSync(
  `${OUT}/imaxt-cover.css`,
  `/* GENERATED by design/tools/build-imaxt-mock.mjs. Do not edit. Typographic covers for artboards that use mock.css. */
.dm { --font-display: 'Archivo Variable', 'Archivo', system-ui, sans-serif; --font-mono: 'Space Mono', ui-monospace, monospace; --font-fraunces: 'Fraunces Variable', 'Fraunces', Georgia, serif; }
${coverRoot.toString()}\n`,
);

// ---------- Artboards ----------
const doc = parse(read('dist/imaxt/index.html'));
const walk = (n, f) => { f(n); (n.childNodes ?? []).forEach((c) => walk(c, f)); };
const find = (n, pred) => { let hit; walk(n, (x) => { if (!hit && pred(x)) hit = x; }); return hit; };
const all = (n, pred) => { const out = []; walk(n, (x) => pred(x) && out.push(x)); return out; };
const attr = (n, name) => n.attrs?.find((a) => a.name === name)?.value;
const setAttr = (n, name, value) => { const a = n.attrs.find((x) => x.name === name); if (a) a.value = value; else n.attrs.push({ name, value }); };
const hasClass = (n, c) => (attr(n, 'class') ?? '').split(/\s+/).includes(c);
const detach = (n) => { n.parentNode.childNodes = n.parentNode.childNodes.filter((c) => c !== n); };
const appendHtml = (n, html) => { for (const c of parseFragment(html).childNodes) { c.parentNode = n; n.childNodes.push(c); } };
const esc = (s) => s.replace(/&/g, '&amp;').replace(/</g, '&lt;');

const body = find(doc, (n) => n.tagName === 'body');
all(body, (n) => n.tagName === 'script' || n.tagName === 'template').forEach(detach);
// Unwrap Astro islands (keep the server-rendered markup inside).
all(body, (n) => n.tagName === 'astro-island').forEach((n) => {
  const i = n.parentNode.childNodes.indexOf(n);
  n.childNodes.forEach((c) => (c.parentNode = n.parentNode));
  n.parentNode.childNodes.splice(i, 1, ...n.childNodes);
});

// Show the state JavaScript would produce: Scrolly stage and CodeWalk highlight.
all(body, (n) => hasClass(n, 'imx-scrolly')).forEach((root) => {
  setAttr(root, 'data-js', '');
  const holder = find(root, (n) => hasClass(n, 'imx-scrolly-slides'));
  const beats = all(root, (n) => hasClass(n, 'imx-beat'));
  beats.forEach((b, i) => {
    appendHtml(holder, `<div class="imx-slide${i === 0 ? ' on' : ''}"><div class="imx-slide-big">${esc(attr(b, 'data-stage') ?? '')}</div>${attr(b, 'data-sub') ? `<div class="imx-slide-sub imx-label">${esc(attr(b, 'data-sub'))}</div>` : ''}</div>`);
    if (i === 0) setAttr(b, 'class', `${attr(b, 'class')} on`);
  });
});
all(body, (n) => hasClass(n, 'imx-walk')).forEach((walkEl) => {
  setAttr(walkEl, 'data-js', '');
  const steps = all(walkEl, (n) => hasClass(n, 'imx-walk-step'));
  if (!steps.length) return;
  setAttr(steps[0], 'aria-pressed', 'true');
  const on = new Set();
  attr(steps[0], 'data-lines').split(',').forEach((p) => { const [a, b] = p.split('-').map(Number); for (let k = a; k <= (b || a); k++) on.add(k); });
  all(walkEl, (n) => n.tagName === 'span' && hasClass(n, 'line')).forEach((l, idx) => { if (!on.has(idx + 1)) setAttr(l, 'class', `${attr(l, 'class')} dim`); });
});

// The Lab page only documents diagrams (they are built from Markdown fences), so pull the live
// SVG figures from three built posts into its Diagrams section.
const figures = ['forward-proxies-explained', 'systems-notes/consensus-without-the-hand-waving', 'axon/the-ingestion-pipeline']
  .map((slug) => find(parse(read(`dist/${slug}/index.html`)), (n) => n.tagName === 'figure' && hasClass(n, 'diagram')))
  .filter(Boolean);
const h2 = find(body, (n) => n.tagName === 'h2' && n.childNodes.some((c) => c.value === 'Diagrams'));
if (h2 && figures.length) {
  const siblings = h2.parentNode.childNodes;
  const para = siblings.slice(siblings.indexOf(h2) + 1).find((n) => n.tagName === 'p');
  const at = siblings.indexOf(para) + 1;
  const holder = parseFragment('<div class="imx-diagram-set"></div>').childNodes[0];
  figures.forEach((f) => { f.parentNode = holder; holder.childNodes.push(f); });
  holder.parentNode = h2.parentNode;
  siblings.splice(at, 0, holder);
}

// The design boards show the visuals; the source samples live on the Lab page itself.
const inside = (n, cls) => { for (let p = n.parentNode; p; p = p.parentNode) if (p.attrs && hasClass(p, cls)) return true; return false; };
all(body, (n) => n.tagName === 'pre' && hasClass(n, 'astro-code') && !inside(n, 'imx-walk')).forEach(detach);
// Beats are sized in viewport heights on the site; give them a fixed, compact height on a static board.
all(body, (n) => hasClass(n, 'imx-beat')).forEach((b) => setAttr(b, 'style', 'min-height:200px'));

const header = find(body, (n) => n.tagName === 'header' && hasClass(n, 'hdr'));
const footer = find(body, (n) => n.tagName === 'footer' && hasClass(n, 'foot'));
const hero = find(body, (n) => n.tagName === 'section' && hasClass(n, 'wrap'));
const content = all(body, (n) => n.tagName === 'div' && hasClass(n, 'wrap')).find((n) => find(n, (x) => hasClass(x, 'prose')));
const prose = find(content, (n) => hasClass(n, 'prose'));
const coversGrid = content.childNodes.find((n) => n.tagName === 'div' && n !== prose && attr(n, 'style')?.includes('grid-template-columns'));

// Split the prose into sections at each h2.
const sections = [];
for (const n of prose.childNodes) {
  if (n.tagName === 'h2') sections.push({ title: n.childNodes.map((c) => c.value ?? '').join(''), html: '' });
  if (sections.length && (n.nodeName !== '#text')) sections.at(-1).html += serialize({ nodeName: '#document-fragment', childNodes: [n] });
}
const pick = (titles) => sections.filter((x) => titles.includes(x.title)).map((x) => x.html).join('\n');
const proseWrap = (html) => `<div class="wrap" style="padding-bottom:96px"><div class="prose" style="max-width:860px;margin:0">${html}</div></div>`;
const fragment = (n) => (n ? serialize({ nodeName: '#document-fragment', childNodes: [n] }) : '');
const part1 = ['How to use it', 'Statement', 'Stat and StatRow', 'PullQuote', 'Compare', 'Steps', 'Timeline', 'Bars', 'Sidenote'];
const part2 = ['CodeWalk', 'Marquee', 'Heatmap', 'CurvedText', 'Scrolly', 'TypeLab', 'Diagrams'];
const part3 = ['Typographic covers'];
const part1All = [...part1, ...part3];
const boards = {
  Imaxt: [fragment(header), fragment(hero), proseWrap(pick(part1All)), `<div class="wrap" style="padding-bottom:96px">${fragment(coversGrid)}</div>`, fragment(footer)],
  Imaxt2: [fragment(header), proseWrap(pick(part2)), fragment(footer)],
};
for (const [name, parts] of Object.entries(boards)) if (parts.join('').includes('{{')) throw new Error(`${name} contains "{{", which the canvas would treat as a template hole.`);

const FONTS = 'https://fonts.googleapis.com/css2?family=Archivo:wdth,wght@62..125,100..900&family=Space+Mono:wght@400;700&family=Source+Serif+4:ital,opsz,wght@0,8..60,400..700;1,8..60,400..600&family=Fraunces:ital,opsz,wght@0,9..144,100..900;1,9..144,100..900&display=swap';
const artboard = (title, markup, height, width) => `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<title>${title}</title>
<script src="./support.js"></script>
<link rel="stylesheet" href="site.css">
</head>
<body>
<x-dc>
<helmet>
<link rel="preconnect" href="https://fonts.googleapis.com">
<link href="${FONTS}" rel="stylesheet">
<style>body{margin:0}</style>
</helmet>
<div class="dm {{theme}}">
${markup}
</div>
</x-dc>
<script type="text/x-dc" data-dc-script data-props='{"dark":{"editor":"boolean","default":false,"section":"Palette"},"$preview":{"width":${width},"height":${height}}}'>
class Component extends DCLogic {
  renderVals() {
    return { theme: this.props.dark ? 'dark' : 'light' };
  }
}
</script>
</body>
</html>
`;
const titles = { Imaxt: 'Imaxt blocks 1: text, data and covers', Imaxt2: 'Imaxt blocks 2: code, motion, diagrams' };
for (const [name, parts] of Object.entries(boards)) {
  fs.writeFileSync(`${OUT}/${name}.dc.html`, artboard(titles[name], parts.join('\n'), arg(`${name}-height`, 4000), 1440));
  fs.writeFileSync(`${OUT}/${name}Mobile.dc.html`, artboard(`${titles[name]} (mobile)`, parts.join('\n'), arg(`${name}-mobile-height`, 6000), 390));
}
console.log('wrote site.css, imaxt-cover.css and the Imaxt boards');
